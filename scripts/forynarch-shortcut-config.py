#!/usr/bin/env python3
"""Remap trusted system actions, reject collisions and write user-owned Lua."""
import fcntl
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile

CATALOG = Path("/usr/share/forynarch/shortcut-catalog.json")
MODIFIERS = {"WIN":"SUPER", "META":"SUPER", "SUPER":"SUPER", "CTRL":"CTRL", "CONTROL":"CTRL", "ALT":"ALT", "SHIFT":"SHIFT"}
ORDER = ("SUPER", "CTRL", "ALT", "SHIFT")
ALIASES = {"ENTER":"RETURN", "ESC":"ESCAPE", ".":"PERIOD", ",":"COMMA", " ":"SPACE", "-":"MINUS", "=":"EQUAL", "SUPER":"SUPER_L"}


def canonical(value):
    if not isinstance(value, str) or len(value) > 120:
        raise ValueError("Use a shortcut of at most 120 characters.")
    if not value.strip():
        return ""
    parts = [part.strip().upper() for part in value.split("+")]
    modifiers = []
    for part in parts[:-1]:
        if part not in MODIFIERS or MODIFIERS[part] in modifiers:
            raise ValueError("Use Super, Ctrl, Alt or Shift once before the key.")
        modifiers.append(MODIFIERS[part])
    key = ALIASES.get(parts[-1], parts[-1])
    if not re.fullmatch(r"[A-Z0-9_]+|MOUSE:27[2-9]|CODE:[0-9]{1,3}", key):
        raise ValueError("Use a key name such as Space, Return, F2 or mouse:273.")
    return " + ".join([mod for mod in ORDER if mod in modifiers] + [key.lower() if ":" in key else key])


def current_bindings():
    result = subprocess.run(["hyprctl", "-j", "binds"], text=True, capture_output=True, timeout=5, check=True)
    return json.loads(result.stdout)


def native_key(row):
    mask = row.get("modmask", 0)
    modifiers = [name for bit, name in ((64,"SUPER"),(4,"CTRL"),(8,"ALT"),(1,"SHIFT")) if mask & bit]
    key = row.get("key") or ("code:" + str(row.get("keycode", 0)))
    return canonical(" + ".join(modifiers + [key]))


def conflicts(rows, overrides, live, previous):
    chosen = {}
    problems = []
    managed = {(row["title"], canonical(row["keys"])) for row in rows}
    managed.update((row["title"], canonical(previous.get(row["id"], row["keys"]))) for row in rows)
    touched = {key for _, key in managed if key}
    for row in rows:
        key = canonical(overrides.get(row["id"], row["keys"]))
        if not key:
            continue
        if key in chosen:
            problems.append({"key":key, "action":row["title"], "other":chosen[key]})
        chosen[key] = row["title"]
    for row in live:
        if row.get("non_consuming") and row.get("description") in {"Observe floating drag", "Finish floating snap"}:
            continue
        key = native_key(row)
        if key in (set(chosen) | touched) and (row.get("description", ""), key) not in managed:
            problems.append({"key":key,"action":chosen.get(key, "Existing system shortcut"),"other":row.get("description") or "Additional Hyprland binding"})
    return problems


def render(rows, overrides, previous):
    keys = {canonical(row["keys"]) for row in rows}
    keys.update(canonical(value) for value in previous.values())
    lines = ["-- User shortcut overrides generated by Forynarch Settings."]
    lines.extend("hl.unbind(" + json.dumps(key) + ")" for key in sorted(keys) if key)
    for row in rows:
        key = canonical(overrides.get(row["id"], row["keys"]))
        if not key:
            continue
        identifier = json.dumps(row["id"])
        lines.append("hl.bind(" + json.dumps(key) + ",forynarch_shortcuts[" + identifier + "].dispatcher,forynarch_shortcuts[" + identifier + "].flags)")
    observed = sorted(key for key in keys if key and key.endswith("mouse:272"))
    lines.append("if _G.forynarch_snap_rebind then _G.forynarch_snap_rebind(" + json.dumps(observed).replace("[", "{").replace("]", "}") + ") end")
    return "\n".join(lines) + "\n"


def atomic(path, value):
    fd, temporary = tempfile.mkstemp(prefix=".shortcuts-", dir=path.parent)
    try:
        with os.fdopen(fd, "w") as stream:
            stream.write(value)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def apply(module, text, path, document, reload=False):
    old = module.read_text() if module.exists() else None
    old_document = path.read_text() if path.exists() else None
    atomic(module, text)
    try:
        result = subprocess.run(["hyprctl", "eval", "dofile(" + json.dumps(str(module)) + ")"], text=True, capture_output=True, timeout=8, check=True)
        if result.stdout.strip() != "ok":
            raise ValueError("The compositor rejected the shortcut configuration.")
        atomic(path, document)
        if reload:
            subprocess.run(["hyprctl", "reload"], capture_output=True, timeout=8, check=True)
    except (ValueError, OSError, subprocess.SubprocessError):
        if old is None:
            module.unlink(missing_ok=True)
        else:
            atomic(module, old)
        if old_document is None:
            path.unlink(missing_ok=True)
        else:
            atomic(path, old_document)
        subprocess.run(["hyprctl", "reload"], capture_output=True, timeout=8, check=False)
        raise


def main():
    rows = json.loads(CATALOG.read_text())["bindings"]
    known = {row["id"] for row in rows}
    base = Path(os.environ.get("XDG_CONFIG_HOME", str(Path.home() / ".config")))
    directory = base / "forynarch"
    directory.mkdir(parents=True, exist_ok=True)
    module = base / "hypr/bindings-user.lua"
    module.parent.mkdir(parents=True, exist_ok=True)
    path = directory / "shortcuts.json"
    action = sys.argv[1] if len(sys.argv) > 1 else "status"
    with open(directory / "shortcuts.lock", "w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        try:
            document = json.loads(path.read_text()) if path.exists() else {"version":1,"bindings":{}}
        except ValueError:
            if action != "reset-all":
                raise ValueError("Invalid shortcut file. Restore defaults to recover it.") from None
            document = {"version":1,"bindings":{}}
        if not isinstance(document, dict) or document.get("version") != 1 or not isinstance(document.get("bindings"), dict):
            if action != "reset-all":
                raise ValueError("Invalid shortcut file. Restore defaults to recover it.")
            document = {"version":1,"bindings":{}}
        try:
            previous = {key:canonical(value) for key, value in document["bindings"].items() if key in known}
        except ValueError:
            if action != "reset-all":
                raise ValueError("Invalid shortcut file. Restore defaults to recover it.") from None
            previous = {}
        overrides = dict(previous)
        if action in {"set", "check", "reset"}:
            if len(sys.argv) != (3 if action == "reset" else 4) or sys.argv[2] not in known:
                raise ValueError("Select a known system action.")
            identifier = sys.argv[2]
            if action == "reset":
                overrides.pop(identifier, None)
            else:
                overrides[identifier] = canonical(sys.argv[3])
        elif action == "reset-all":
            if len(sys.argv) != 2:
                raise ValueError("Invalid reset request.")
            overrides = {}
        elif action not in {"status", "refresh"} or len(sys.argv) > 2:
            raise ValueError("Unknown shortcut action.")
        live = current_bindings()
        problems = conflicts(rows, overrides, live, previous)
        if action == "status":
            print(json.dumps({"rows":[dict(id=row["id"],title=row["title"],keys=overrides.get(row["id"],canonical(row["keys"])),defaultKeys=canonical(row["keys"]),custom=row["id"] in overrides) for row in rows],"conflicts":problems}))
        elif action == "check":
            print(json.dumps({"valid":not problems,"conflicts":problems}))
        else:
            if problems:
                first = problems[0]
                raise ValueError(first["key"] + " conflicts with " + first["other"] + ". Change or disable that binding first.")
            text = render(rows, overrides, previous)
            apply(module, text, path, json.dumps({"version":1,"bindings":overrides}, indent=2) + "\n", reload=action == "reset-all")
            print(json.dumps({"saved":True}))
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (ValueError, OSError, subprocess.SubprocessError, KeyError) as error:
        print(str(error) if isinstance(error, ValueError) else "Shortcuts could not be updated. Use this control in an active Hyprland session.",file=sys.stderr)
        sys.exit(1)
