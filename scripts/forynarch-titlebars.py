#!/usr/bin/env python3
"""Persist exact app-class titlebar exceptions and apply bounded Hyprland rules."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile


def locations():
    config = Path(os.environ.get('XDG_CONFIG_HOME', str(Path.home() / '.config')))
    state = Path(os.environ.get('XDG_STATE_HOME', str(Path.home() / '.local/state')))
    return config / 'forynarch/titlebars.json', config / 'hypr/titlebar-rules.lua', state / 'forynarch/titlebar-classes.json'


def atomic(path, text):
    path.parent.mkdir(parents=True, mode=0o700, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix='.titlebars-', dir=path.parent)
    try:
        with os.fdopen(fd, 'w', encoding='utf-8', newline='\n') as stream:
            stream.write(text)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def load(path, fallback):
    if not path.exists():
        return fallback
    if path.is_symlink() or path.stat().st_size > 65536:
        raise ValueError('Titlebar preferences must be a local file under 64 KB.')
    return json.loads(path.read_text(encoding='utf-8'))


def catalog():
    path = Path('/usr/share/forynarch/titlebar-defaults.json')
    if not path.is_file():
        path = Path(__file__).resolve().parents[1] / 'config/forynarch/titlebar-defaults.json'
    value = load(path, None)
    if not isinstance(value, dict) or value.get('schema') != 1 or not isinstance(value.get('groups'), list):
        raise ValueError('The titlebar app catalog is unavailable.')
    return value['groups']


def app_class(value):
    if not isinstance(value, str) or not 0 < len(value) <= 160 or re.search(r'[\x00-\x1f\x7f]', value):
        raise ValueError('Enter an exact application class of 1–160 characters, without control characters.')
    return value


def preferences():
    value = load(locations()[0], {'schema': 1, 'enabled': True, 'useDefaults': True, 'exclusions': [], 'inclusions': []})
    if not isinstance(value, dict) or set(value) != {'schema', 'enabled', 'useDefaults', 'exclusions', 'inclusions'} or value['schema'] != 1:
        raise ValueError('Titlebar preferences have an unsupported format.')
    if any(type(value[key]) is not bool for key in ['enabled', 'useDefaults']):
        raise ValueError('Titlebar switches must be true or false.')
    for key in ['exclusions', 'inclusions']:
        if not isinstance(value[key], list) or len(value[key]) > 64:
            raise ValueError('Keep at most 64 titlebar exceptions of each kind.')
        value[key] = sorted(set(app_class(item).casefold() for item in value[key]))
    if set(value['exclusions']) & set(value['inclusions']):
        raise ValueError('An app cannot use both native and Forynarch titlebars.')
    return value


def default_native(value, groups):
    return any(value.casefold() in [item.casefold() for item in group['classes']] for group in groups)


def native(value, prefs, groups):
    key = value.casefold()
    if not prefs['enabled'] or key in prefs['exclusions']:
        return True
    if key in prefs['inclusions']:
        return False
    return prefs['useDefaults'] and default_native(key, groups)


def rule(name, pattern, hide, enabled=True):
    return ('hl.window_rule({name=' + json.dumps(name) + ',match={class=' + json.dumps(pattern, ensure_ascii=False) +
            ',float=true},["hyprbars:no_bar"]="' + str(hide).lower() + '",enabled=' + str(enabled).lower() + '})')


def rules(prefs, groups, previous=()):
    result = ['-- Generated by forynarch-titlebars; edit titlebars.json or use Settings > Desktop.']
    for group in groups:
        pattern = '(?i)^(' + '|'.join(re.escape(item) for item in group['classes']) + ')$'
        result.append(rule('forynarch-native-' + group['id'], pattern, True, prefs['useDefaults']))
    active = set(prefs['exclusions'] + prefs['inclusions'])
    for key in sorted(set(previous) | active):
        name = 'forynarch-titlebar-app-' + hashlib.sha256(key.encode()).hexdigest()[:16]
        result.append(rule(name, '(?i)^' + re.escape(key) + '$', not prefs['enabled'] or key in prefs['exclusions'], key in active))
    result.append(rule('forynarch-titlebars-disabled', '.*', True, not prefs['enabled']))
    return '\n'.join(result) + '\n'


def apply(prefs, groups):
    _, path, state = locations()
    previous = load(state, [])
    if not isinstance(previous, list) or len(previous) > 128:
        previous = []
    previous = [app_class(key).casefold() for key in previous]
    atomic(path, rules(prefs, groups, previous))
    active = sorted(set(prefs['exclusions'] + prefs['inclusions']))
    atomic(state, json.dumps(active) + '\n')
    if os.environ.get('HYPRLAND_INSTANCE_SIGNATURE'):
        command = 'if _G.forynarch_titlebars then dofile(' + json.dumps(str(path), ensure_ascii=False) + ') end'
        result = subprocess.run(['hyprctl', 'eval', command], text=True, capture_output=True, timeout=5)
        if result.returncode or 'error' in result.stdout.lower():
            raise ValueError('Preferences were saved, but the desktop could not apply them. Sign out and back in.')


def status(prefs, groups):
    apps = []
    if os.environ.get('HYPRLAND_INSTANCE_SIGNATURE'):
        try:
            result = subprocess.run(['hyprctl', '-j', 'clients'], text=True, capture_output=True, timeout=3, check=True)
            seen = set()
            for client in json.loads(result.stdout):
                key = client.get('class', '')
                if not key or key.casefold() in seen:
                    continue
                app_class(key)
                seen.add(key.casefold())
                name = key
                try:
                    from forynarch_app_identity import identity
                    name = identity(client).get('displayName', key)
                except ImportError:
                    pass
                apps.append({'class': key, 'name': name, 'native': native(key, prefs, groups),
                             'source': 'custom' if key.casefold() in prefs['exclusions'] + prefs['inclusions'] else 'default'})
        except (OSError, ValueError, subprocess.SubprocessError):
            pass
    return {'preferences': prefs, 'defaults': [{'name': g['name'], 'classes': g['classes']} for g in groups],
            'apps': sorted(apps, key=lambda item: item['name'].casefold())}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['status', 'apply', 'set', 'except', 'forget', 'render-defaults'])
    parser.add_argument('key', nargs='?')
    parser.add_argument('value', nargs='?')
    args = parser.parse_args()
    groups = catalog()
    if args.action == 'render-defaults':
        print(rules({'enabled': True, 'useDefaults': True, 'exclusions': [], 'inclusions': []}, groups), end='')
        return
    prefs = preferences()
    if args.action == 'set':
        if args.key not in ['enabled', 'useDefaults'] or args.value not in ['true', 'false']:
            raise ValueError('Use enabled or useDefaults with true or false.')
        prefs[args.key] = args.value == 'true'
    elif args.action in ['except', 'forget']:
        key = app_class(args.key).casefold()
        if args.action == 'except' and args.value not in ['true', 'false']:
            raise ValueError('Choose true for app controls or false for Forynarch controls.')
        prefs['exclusions'] = [item for item in prefs['exclusions'] if item != key]
        prefs['inclusions'] = [item for item in prefs['inclusions'] if item != key]
        if args.action == 'except':
            group = 'exclusions' if args.value == 'true' else 'inclusions'
            if len(prefs[group]) >= 64:
                raise ValueError('Remove an exception before adding more than 64.')
            prefs[group].append(key)
    if args.action in ['set', 'except', 'forget']:
        atomic(locations()[0], json.dumps(prefs, indent=2, ensure_ascii=False) + '\n')
    if args.action != 'status':
        apply(prefs, groups)
    print(json.dumps(status(prefs, groups), ensure_ascii=False))


if __name__ == '__main__':
    try:
        main()
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        print(json.dumps({'error': str(error)}, ensure_ascii=False))
        sys.exit(1)
