#!/usr/bin/env python3
"""On-demand notification settings and Mako history; no additional daemon."""
import fcntl
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile

DEFAULTS={"profile":"normal","timeout":6,"enabled":True,"critical":True,"allow":[]}
MODES=("forynarch-settings","forynarch-custom","do-not-disturb","forynarch-disabled")


def config_home():
    return Path(os.environ.get("XDG_CONFIG_HOME",str(Path.home()/".config")))


def validate(data):
    if not isinstance(data,dict) or set(data)!=set(DEFAULTS):raise ValueError("Choose complete notification settings.")
    if data["profile"] not in {"normal","dnd","custom"}:raise ValueError("Choose a notification profile.")
    if type(data["timeout"]) is not int or not 3<=data["timeout"]<=30:raise ValueError("Choose a duration from 3 to 30 seconds.")
    if any(type(data[k]) is not bool for k in ("enabled","critical")):raise ValueError("Choose whether notifications and critical alerts are allowed.")
    if not isinstance(data["allow"],list) or len(data["allow"])>32:raise ValueError("Choose at most 32 allowed applications.")
    if any(not isinstance(a,str) or not a.strip() or len(a)>100 or any(ord(c)<32 for c in a) for a in data["allow"]):raise ValueError("Application names must contain readable text.")
    return {**data,"allow":sorted(set(a.strip() for a in data["allow"]))}


def load():
    path=config_home()/"forynarch/notifications.json"
    if not path.exists():return dict(DEFAULTS)
    if path.stat().st_size>16384:raise ValueError("The notification settings file is too large.")
    return validate(json.loads(path.read_text()))


def atomic(path,text):
    path.parent.mkdir(parents=True,exist_ok=True,mode=0o700)
    fd,name=tempfile.mkstemp(dir=path.parent,prefix=".notifications-")
    try:
        with os.fdopen(fd,"w") as stream:stream.write(text);stream.flush();os.fsync(stream.fileno())
        os.replace(name,path)
    finally:
        if os.path.exists(name):os.unlink(name)


def render(data):
    lines=["# Generated by Forynarch Notifications. Edit settings through the UI or notifications.json.",
           "[mode=forynarch-settings]",f"default-timeout={data['timeout']*1000}",
           "[mode=forynarch-settings urgency=critical]","default-timeout=0",
           "[mode=forynarch-custom]","invisible=1"]
    for app in data["allow"]:
        escaped=app.replace("\\","\\\\").replace('"','\\"')
        lines += [f'[mode=forynarch-custom app-name="{escaped}"]',"invisible=0"]
    if data["critical"]:lines += ["[mode=forynarch-custom urgency=critical]","invisible=0"]
    lines += ["[mode=do-not-disturb]","invisible=1","[mode=forynarch-disabled]","invisible=1"]
    return "\n".join(lines)+"\n"


def command(*args,check=True):
    result=subprocess.run(["makoctl",*args],capture_output=True,text=True,timeout=4)
    if check and result.returncode:raise ValueError("The notification service is unavailable. Try again after signing in.")
    return result


def prepare(data):
    atomic(config_home()/"forynarch/notifications.mako",render(data))
    path=config_home()/"mako/config"
    # Absolute paths also support an explicitly relocated XDG_CONFIG_HOME.
    marker="include="+str(config_home()/"forynarch/notifications.mako")
    source=path.read_text() if path.exists() else "max-history=50\n"
    source="\n".join(line for line in source.splitlines() if line.strip() not in {marker,"include=~/.config/forynarch/notifications.mako"})
    atomic(path,marker+"\n"+source.lstrip("\n").rstrip()+"\n")


def apply(data):
    prepare(data)
    command("reload")
    wanted={"forynarch-settings"}
    if data["profile"]=="dnd":wanted.add("do-not-disturb")
    if data["profile"]=="custom":wanted.add("forynarch-custom")
    if not data["enabled"]:wanted.add("forynarch-disabled")
    args=["mode"]
    for mode in MODES:args += ["-a" if mode in wanted else "-r",mode]
    command(*args)
    if os.environ.get("WAYLAND_DISPLAY"):
        try:
            subprocess.run(["qs","-c","forynarch","ipc","call","appearance","notificationMode",str(data["profile"]=="dnd").lower()],capture_output=True,timeout=.5)
        except (OSError,subprocess.SubprocessError):
            pass  # A busy panel must not roll back an already applied notification policy.


def normalize(rows,history=False):
    if not isinstance(rows,list):return []
    result=[]
    for row in rows[:100]:
        if not isinstance(row,dict) or type(row.get("id")) is not int:continue
        actions=row.get("actions",{})
        result.append({"id":row["id"],"app":str(row.get("app_name") or "Application")[:100],
                       "title":str(row.get("summary") or "Notification")[:500],"body":str(row.get("body") or "")[:4000],
                       "critical":row.get("urgency")=="critical","history":history,
                       "actions":[{"id":key,"label":str(value)[:100]} for key,value in actions.items()][:8] if isinstance(actions,dict) else []})
    return result


def status():
    data=load();modes=command("mode",check=False)
    if modes.returncode:return {"settings":data,"available":False,"current":[],"history":[],"dnd":False}
    current=normalize(json.loads(command("list","-j").stdout))
    history=normalize(json.loads(command("history","-j").stdout),True)
    return {"settings":data,"available":True,"current":current,"history":history,
            "dnd":"do-not-disturb" in modes.stdout.splitlines()}


def main():
    action=sys.argv[1] if len(sys.argv)>1 else "status"
    if action=="status":print(json.dumps(status()));return
    directory=config_home()/"forynarch";directory.mkdir(parents=True,exist_ok=True)
    with open(directory/"notifications.lock","w") as lock:
        fcntl.flock(lock,fcntl.LOCK_EX)
        data=load()
        if action=="prepare":prepare(data);return
        if action=="initialize":apply(data);return
        if action in {"set","dismiss","invoke","clear"}:
            raw=sys.stdin.buffer.read(16385)
            if len(raw)>16384:raise ValueError("The notification request is too large.")
            request=json.loads(raw or b"{}")
            if not isinstance(request,dict):raise ValueError("Choose a notification operation.")
        if action=="set":
            data=validate(request);old=load()
            try:apply(data)
            except (ValueError,OSError,subprocess.SubprocessError):
                prepare(old);command("reload",check=False);raise
            atomic(directory/"notifications.json",json.dumps(data)+"\n")
        elif action in {"dnd","toggle"}:
            value=("do-not-disturb" not in command("mode").stdout.splitlines()) if action=="toggle" else len(sys.argv)==3 and sys.argv[2]=="on"
            if action=="dnd" and (len(sys.argv)!=3 or sys.argv[2] not in {"on","off"}):raise ValueError("Choose on or off.")
            data["profile"]="dnd" if value else "normal";apply(data);atomic(directory/"notifications.json",json.dumps(data)+"\n")
        elif action=="clear":
            if request!={}:raise ValueError("Choose clear notifications.")
            command("dismiss","--all")
        elif action in {"dismiss","invoke"}:
            if type(request.get("id")) is not int or not 0<request["id"]<2**32:raise ValueError("Select a current notification.")
            if action=="dismiss":
                if set(request)!={"id"}:raise ValueError("Select a current notification.")
                command("dismiss","-n",str(request["id"]))
            else:
                if set(request)!={"id","action"} or not isinstance(request["action"],str) or len(request["action"])>200:raise ValueError("Select a notification action.")
                command("invoke","-n",str(request["id"]),request["action"])
        else:raise ValueError("Choose a notification operation.")
        print(json.dumps(status()))


if __name__=="__main__":
    try:main()
    except (OSError,ValueError,subprocess.SubprocessError) as error:
        print(json.dumps({"error":str(error) if isinstance(error,ValueError) else "Notification settings could not complete the operation."}),file=sys.stderr);sys.exit(1)
