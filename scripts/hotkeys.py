"""Author/build-time shortcut compiler. Never installed as a target Python helper."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
PAGES = {"Appearance", "Files", "Default Apps", "Date & Time", "Notifications", "Virtual Machines", "Panel", "Desktop", "Network", "Bluetooth", "Sound", "Displays", "Power", "Input", "Storage", "Privacy", "Shortcuts", "About"}


def bindings():
    document = json.loads((ROOT / "config/forynarch/hotkeys.json").read_text())
    if document.get("version") != 1:
        raise ValueError("Unsupported hotkey schema")
    rows = list(document["bindings"])
    rows += [
        dict(keys="SUPER + D",title="Show desktop / restore windows",action="exec",command="forynarch-window-control show-desktop"),
        dict(keys="SUPER + L",title="Toggle whole-workspace floating",action="exec",command="forynarch-hotkey layout-toggle"),
        dict(keys="SUPER + CTRL + M",title="Minimize window",action="exec",command="forynarch-window-control minimize"),
        dict(keys="SUPER + CTRL + SHIFT + M",title="Restore minimized window",action="exec",command="forynarch-window-control restore-last"),
        dict(keys="SUPER + mouse:272",title="Move window",action="lua",code="hl.dsp.window.drag()",flags={"mouse":True},hidden=True),
        dict(keys="SUPER + mouse:273",title="Resize window",action="lua",code="hl.dsp.window.resize()",flags={"mouse":True},hidden=True),
        dict(keys="SUPER + GRAVE",title="Scratchpad",action="lua",code='hl.dsp.workspace.toggle_special("magic")'),
        dict(keys="SUPER + SHIFT + GRAVE",title="Send to scratchpad",action="lua",code='hl.dsp.window.move({workspace="special:magic"})'),
        dict(keys="SUPER + CTRL + Z",title="Zoom",action="exec",command="forynarch-hotkey zoom"),
        dict(keys="SUPER + CTRL + ALT + Z",title="Reset zoom",action="exec",command="forynarch-hotkey zoom-reset"),
        dict(keys="SUPER + ALT + G",title="Ungroup window",action="lua",code='hl.dsp.window.move({out_of_group=true})'),
        dict(keys="XF86AudioNext",title="Next track",action="exec",command="forynarch-hotkey media next",flags={"locked":True}),
        dict(keys="XF86AudioPrev",title="Previous track",action="exec",command="forynarch-hotkey media previous",flags={"locked":True}),
        dict(keys="XF86AudioPlay",title="Play / pause",action="exec",command="forynarch-hotkey media toggle",flags={"locked":True}),
        dict(keys="XF86AudioPause",title="Play / pause",action="exec",command="forynarch-hotkey media toggle",flags={"locked":True}),
    ]
    for direction in ("left", "right", "up", "down"):
        rows.append(dict(keys=f"SUPER + ALT + {direction}",title=f"Group {direction}",action="lua",code=f'hl.dsp.window.move({{into_group="{direction[0]}"}})'))
        rows.append(dict(keys=f"SUPER + {direction}", title=f"Focus {direction}", action="lua",
                         code=f'function() hl.dispatch(hl.dsp.focus({{direction="{direction[0]}"}})); local window=hl.get_active_window(); if window and window.floating then hl.dispatch(hl.dsp.window.bring_to_top()) end end', origin="Forynarch"))
        rows.append(dict(keys=f"SUPER + SHIFT + {direction}", title=f"Swap {direction}", action="lua",
                         code=f'hl.dsp.window.swap({{direction="{direction[0]}"}})', origin="Forynarch"))
    for slot in range(1, 6):
        rows.append(dict(keys=f"SUPER + ALT + {slot}",title=f"Group tab {slot}",action="lua",code=f"hl.dsp.group.active({{index={slot}}})"))
        for mods, verb, title in (("SUPER", "focus", "Local slot"), ("SUPER + SHIFT", "move", "Send to local slot"),
                                  ("SUPER + SHIFT + ALT", "move-silent", "Send without following")):
            rows.append(dict(keys=f"{mods} + {slot}", title=f"{title} {slot}", action="exec",
                             command=f"forynarch-workspace {verb} {slot}", origin="Forynarch"))
    seen = set()
    for row in rows:
        parts = row["keys"].upper().split(" + ")
        identity = (tuple(sorted(parts[:-1])), parts[-1])
        if identity in seen or not re.fullmatch(r"[A-Za-z0-9_:+ ]+", row["keys"]):
            raise ValueError("Duplicate or invalid shortcut")
        seen.add(identity)
        if row["action"] not in ("exec", "lua"):
            raise ValueError("Invalid action")
    return rows


def lua_text():
    # Source-owned declarations only; user app names and settings never become Lua.
    lines = ["-- Generated by scripts/hotkeys.py. Edit hotkeys.json, not this file.", "forynarch_shortcuts = {}"]
    for key in ["SUPER + ESCAPE", "SUPER + M", "SUPER + SHIFT + S", *[f"SUPER{mods} + {i}" for mods in ("", " + SHIFT") for i in (6, 7, 8, 9, 0)]]:
        lines.append(f"hl.unbind({json.dumps(key)})")
    for row in bindings():
        key = json.dumps(row["keys"])
        code = row.get("code") if row["action"] == "lua" else f'hl.dsp.exec_cmd({json.dumps(row["command"])})'
        flags = dict(row.get("flags", {}), description=row["title"])
        flag_text = ",".join(f"{key}={json.dumps(value)}" for key, value in flags.items())
        identifier = json.dumps(hashlib.sha256(row["keys"].encode()).hexdigest()[:16])
        lines += [f"hl.unbind({key})", f"forynarch_shortcuts[{identifier}] = {{dispatcher={code},flags={{{flag_text}}}}}",
                  f"hl.bind({key}, forynarch_shortcuts[{identifier}].dispatcher, forynarch_shortcuts[{identifier}].flags)"]
    return "\n".join(lines) + "\n"


def guide_rows():
    rows = [dict(title=r["title"], keys=r["keys"].replace("SUPER", "Super").replace("SHIFT", "Shift").replace("CTRL", "Ctrl").replace("ALT", "Alt").split(" + "), origin=r.get("origin", "Omarchy-compatible")) for r in bindings() if not r.get("hidden")]
    rows += [
        dict(keys="SUPER + D",title="Show desktop / restore windows",action="exec",command="forynarch-window-control show-desktop"),dict(title="Move window",keys=["Super","Left drag"],origin="Forynarch"),dict(title="Resize window",keys=["Super","Right drag"],origin="Forynarch")]
    return rows

def js_text():
    rows = guide_rows()
    return ".pragma library\n// Generated from the shared hotkey manifest.\nvar rows = " + json.dumps(rows, indent=2) + ";\n"

def catalog_text():
    rows=[]
    for row in bindings():
        code=row.get("code") if row["action"]=="lua" else "hl.dsp.exec_cmd("+json.dumps(row["command"])+")"
        rows.append(dict(id=hashlib.sha256(row["keys"].encode()).hexdigest()[:16],title=row["title"],
                         keys=row["keys"],code=code,flags=row.get("flags",{})))
    return json.dumps({"version":1,"bindings":rows},indent=2)+"\n"

def text_text():
    return "FORYNARCH — Keyboard shortcuts\n\n" + "\n".join(f'{" + ".join(r["keys"]):36} {r["title"]}' for r in guide_rows()) + "\n\nWorkspace slots 1–5 belong to the focused monitor.\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = [(ROOT / "config/hypr/bindings.lua", lua_text()), (ROOT / "config/quickshell/forynarch/HotkeysModel.js", js_text()), (ROOT / "config/forynarch/hotkeys.txt", text_text()), (ROOT / "config/forynarch/shortcut-catalog.json",catalog_text())]
    for path, content in outputs:
        if args.check:
            if path.read_text() != content:
                raise SystemExit("Hotkey outputs are stale")
        else:
            path.write_text(content, encoding="utf-8", newline="\n")
